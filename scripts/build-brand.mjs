// ---- 500x500 PNG exports, logo centred with ~12% padding ----
function squarePng(bg) {
  const S = 500
  const pad = S * 0.12
  const scale = (S - pad * 2) / LOGO_W
  const h = LOGO_H * scale
  const y = (S - h) / 2
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}">${bg ? `<rect width="${S}" height="${S}" fill="${bg}"/>` : ''}<g transform="translate(${pad} ${r2(y)}) scale(${r2(scale * 1000) / 1000})" fill="${INK}"><path d="${MARK_RING}"/><path d="${MARK_ARROW}"/><path d="${logoWord.d}"/></g></svg>`
  return new Resvg(svg, { fitTo: { mode: 'original' }, background: bg ? bg : 'rgba(0,0,0,0)' }).render().asPng()
}
fs.writeFileSync(path.join(root, 'public/brand/logo-500.png'), squarePng(ACCENT))
fs.writeFileSync(path.join(root, 'public/brand/logo-500-transparent.png'), squarePng(null))

// ---- App icons (apple-touch-icon, PWA 192/512): the mark on the accent square ----
// The mark sits inside the central 64% so the icons stay safe as maskable icons.
function iconPng(S) {
  const inner = S * 0.64
  const scale = inner / 64
  const off = (S - inner) / 2
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}"><rect width="${S}" height="${S}" fill="${ACCENT}"/><g transform="translate(${r2(off)} ${r2(off)}) scale(${r2(scale * 1000) / 1000})" fill="${INK}"><path d="${MARK_RING}"/><path d="${MARK_ARROW}"/></g></svg>`
  return new Resvg(svg, { fitTo: { mode: 'original' } }).render().asPng()
}
fs.writeFileSync(path.join(root, 'public/apple-touch-icon.png'), iconPng(180))
fs.writeFileSync(path.join(root, 'public/icon-192.png'), iconPng(192))
fs.writeFileSync(path.join(root, 'public/icon-512.png'), iconPng(512))

