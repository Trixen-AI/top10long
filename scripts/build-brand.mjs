// Builds the Top10Long brand assets from one source of truth.
//   node scripts/build-brand.mjs
// Outputs:
//   src/brand/paths.ts                 path data used by the React components (logo, hero tiles, outline wordmark)
//   public/brand/logo.svg              outlined logo (mark + wordmark)
//   public/brand/logo-500.png          500x500 on the brand background
//   public/brand/logo-500-transparent.png
//   public/favicon.svg                 the mark on its own
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'
import { Resvg } from '@resvg/resvg-js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const font = (file) => {
  const buf = fs.readFileSync(path.join(root, 'scripts/fonts', file))
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
}
const black = font('Geist-Black.ttf')
const bold = font('Geist-Bold.ttf')

// Tokens (keep in sync with src/styles/tokens.css)
const ACCENT = '#FFD23F'
const INK = '#0B0B0C'

const r2 = (n) => Math.round(n * 100) / 100

// Lay out text glyph by glyph with custom tracking, return path d + real bounds.
function outline(f, text, size, trackingEm, x0 = 0, baseline = 0) {
  let x = x0
  const parts = []
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity
  const glyphs = f.stringToGlyphs(text)
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, baseline, size)
    const bb = p.getBoundingBox()
    minX = Math.min(minX, bb.x1); minY = Math.min(minY, bb.y1)
    maxX = Math.max(maxX, bb.x2); maxY = Math.max(maxY, bb.y2)
    parts.push(p.toPathData(2))
    let adv = g.advanceWidth * (size / f.unitsPerEm)
    if (i < glyphs.length - 1) adv += f.getKerningValue(g, glyphs[i + 1]) * (size / f.unitsPerEm)
    x += adv + trackingEm * size
  })
  return { d: parts.join(''), minX, minY, maxX, maxY }
}

// ---- Mark: ten ring segments (ten markets) around one upward triangle (one long position) ----
function ringSegments(cx, cy, R, r, count, gapDeg, startDeg) {
  const seg = 360 / count
  const out = []
  const pt = (rad, a) => [r2(cx + rad * Math.cos((a * Math.PI) / 180)), r2(cy + rad * Math.sin((a * Math.PI) / 180))]
  for (let i = 0; i < count; i++) {
    const a0 = startDeg + i * seg + gapDeg / 2
    const a1 = startDeg + (i + 1) * seg - gapDeg / 2
    const [ox0, oy0] = pt(R, a0), [ox1, oy1] = pt(R, a1)
    const [ix1, iy1] = pt(r, a1), [ix0, iy0] = pt(r, a0)
    out.push(`M${ox0} ${oy0}A${R} ${R} 0 0 1 ${ox1} ${oy1}L${ix1} ${iy1}A${r} ${r} 0 0 0 ${ix0} ${iy0}Z`)
  }
  return out.join('')
}
const MARK_RING = ringSegments(32, 32, 31, 22, 10, 9, -90 - 18)
const MARK_ARROW = 'M32 16.5L43.5 40H20.5Z'

// ---- Logo: mark + outlined wordmark (Geist Bold) ----
const LOGO_H = 64
const WORD = 'Top10Long'
const word = outline(bold, WORD, 44, -0.02)
// Centre on the cap height (not the full ink box) so the descender of "g" does not
// pull the word up against the mark.
const cap = outline(bold, 'T', 44, 0)
const capH = cap.maxY - cap.minY
const wordDx = 64 + 14 - word.minX
const wordDy = (LOGO_H - capH) / 2 - cap.minY
const logoWord = outline(bold, WORD, 44, -0.02, wordDx, wordDy)
const LOGO_W = Math.ceil(logoWord.maxX + 1)

// ---- Hero tile wordmark: same box as the reference tile (826 x 221) ----
const TILE_W = 826
const TILE_H = 221
// Fit inside 4px of the box so the 3px stroke variant is never clipped.
function fitCentered(f, text, trackingEm) {
  const probe = outline(f, text, 100, trackingEm)
  const scale = (TILE_W - 4) / (probe.maxX - probe.minX)
  let size = 100 * scale
  const capH = (probe.maxY - probe.minY) * scale
  if (capH > TILE_H - 4) size *= (TILE_H - 4) / capH
  const t = outline(f, text, size, trackingEm)
  const dx = (TILE_W - (t.maxX - t.minX)) / 2 - t.minX
  const dy = (TILE_H - (t.maxY - t.minY)) / 2 - t.minY
  return outline(f, text, size, trackingEm, dx, dy)
}
const tileShifted = fitCentered(black, WORD, -0.03)

const ts = `// Generated by scripts/build-brand.mjs. Do not edit by hand.
// Wordmark letters are Geist (SIL OFL) outlined to paths.
export const MARK = {
  viewBox: '0 0 64 64',
  ring: '${MARK_RING}',
  arrow: '${MARK_ARROW}',
} as const

export const LOGO = {
  width: ${LOGO_W},
  height: ${LOGO_H},
  word: '${logoWord.d}',
} as const

export const TILE = {
  width: ${TILE_W},
  height: ${TILE_H},
  d: '${tileShifted.d}',
} as const
`
fs.writeFileSync(path.join(root, 'src/brand/paths.ts'), ts)

